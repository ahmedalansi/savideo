#!/usr/bin/env python3
"""Generate tokens.css (custom properties, light + dark) and tailwind.theme.css
(Tailwind v4 @theme mapping) from tokens.json and tokens.dark.json.
Run after any token change:  python3 replica/design/build_css.py"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
light = json.load(open(os.path.join(HERE, "tokens.json"), encoding="utf-8"))
dark = json.load(open(os.path.join(HERE, "tokens.dark.json"), encoding="utf-8"))

def colours(c, indent="  "):
    return "\n".join(f"{indent}--sv-color-{k}: {v};" for k, v in c.items())

out = ["/* Generated by build_css.py from tokens.json + tokens.dark.json. Do not edit by hand. */", ":root {"]
out.append(colours(light["color"]))
for k, v in light["font"].items():
    if not k.startswith("_"):
        out.append(f"  --sv-font-{k}: {v};")
for k, t in light["type"].items():
    out.append(f"  --sv-text-{k}: {t['size']/16:g}rem;")
    out.append(f"  --sv-text-{k}-line: {t['line']/16:g}rem;")
    out.append(f"  --sv-text-{k}-weight: {t['weight']};")
for k, v in light["radius"].items():
    out.append(f"  --sv-radius-{k}: {v}px;")
for k, v in light["shadow"].items():
    out.append(f"  --sv-shadow-{k}: {v};")
for k, v in light["motion"].items():
    out.append(f"  --sv-motion-{k}: {v};")
L = light["layout"]
for k in ("content-max", "tool-max", "header-h", "gutter-mobile", "gutter-desktop", "tap-min"):
    out.append(f"  --sv-layout-{k}: {L[k]}px;")
out.append("  color-scheme: light;\n}")
dark_block = colours(dark["color"], "    ")
out.append("@media (prefers-color-scheme: dark) {\n  :root:not([data-theme=\"light\"]) {\n"
           + dark_block + "\n    color-scheme: dark;\n  }\n}")
out.append(":root[data-theme=\"dark\"] {\n" + colours(dark["color"]) + "\n  color-scheme: dark;\n}")
out.append(":root[lang=\"ar\"] { --sv-font-sans: var(--sv-font-arabic); }")
out.append(":root[lang=\"ar\"] body { line-height: 1.7; }")
out.append("@media (prefers-reduced-motion: reduce) {\n  :root { --sv-motion-fast: 0ms; --sv-motion-base: 0ms; --sv-motion-slow: 0ms; }\n}")
open(os.path.join(HERE, "tokens.css"), "w", encoding="utf-8").write("\n".join(out) + "\n")

# Tailwind v4: map roles to utilities (bg-surface, text-muted, border-input, rounded-md ...)
tw = ["/* Generated by build_css.py. Import after tokens.css:",
      "   @import \"tailwindcss\"; @import \"./tokens.css\"; @import \"./tailwind.theme.css\"; */",
      "@theme inline {"]
for k in light["color"]:
    tw.append(f"  --color-{k}: var(--sv-color-{k});")
tw.append("  --color-muted: var(--sv-color-text-muted); /* text-muted utility */")
tw.append("  --spacing: 0.25rem; /* p-1 = 4px, p-4 = 16px, p-6 = 24px */")
for k in ("sans", "arabic", "mono"):
    tw.append(f"  --font-{k}: var(--sv-font-{k});")
for k in light["type"]:
    tw += [f"  --text-{k}: var(--sv-text-{k});",
           f"  --text-{k}--line-height: var(--sv-text-{k}-line);",
           f"  --text-{k}--font-weight: var(--sv-text-{k}-weight);"]
for k in light["radius"]:
    tw.append(f"  --radius-{k}: var(--sv-radius-{k});")
for k in light["shadow"]:
    tw.append(f"  --shadow-{k}: var(--sv-shadow-{k});")
for k, v in L["breakpoints"].items():
    tw.append(f"  --breakpoint-{k}: {v/16:g}rem;")
tw.append(f"  --container-tool: {L['tool-max']/16:g}rem;")
tw.append(f"  --container-content: {L['content-max']/16:g}rem;")
tw.append("  --ease-out: var(--sv-motion-ease);")
tw.append("}")
tw.append("@custom-variant dark (&:where([data-theme=dark], [data-theme=dark] *));")
open(os.path.join(HERE, "tailwind.theme.css"), "w", encoding="utf-8").write("\n".join(tw) + "\n")
print("wrote tokens.css, tailwind.theme.css")
